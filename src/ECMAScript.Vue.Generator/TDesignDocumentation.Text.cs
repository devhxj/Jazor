    private static string? SpecificEnumMeaning(string type, string value)
    {
        if (type.Contains("Button", StringComparison.Ordinal) && value == "round")
            return "圆角长方形按钮";
        if (type.Contains("CascaderValueType", StringComparison.Ordinal) && value == "single")
            return "值仅包含选中节点";
        if (type.Contains("CascaderValueType", StringComparison.Ordinal) && value == "full")
            return "值包含选中节点的完整路径";
        if (type.Contains("DrawerMode", StringComparison.Ordinal))
            return value == "push" ? "抽屉推开页面内容" : "抽屉覆盖页面内容";
        if (type.Contains("FormResetType", StringComparison.Ordinal))
            return value == "empty" ? "重置为空值" : "重置为初始值";
        if (type.Contains("FormScrollToFirstError", StringComparison.Ordinal) && value == "")
            return "不自动滚动到第一个校验错误";
        if (type.Contains("Image", StringComparison.Ordinal) && type.Contains("Fit", StringComparison.Ordinal) && value == "none")
            return "保持图片原始尺寸，不缩放";
        if (type.Contains("TableLayout", StringComparison.Ordinal))
            return value == "fixed" ? "列宽由表格宽度及指定列宽决定" : "列宽根据单元格内容自动计算";
        return null;
    }
