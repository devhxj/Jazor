namespace Jazor.VueHost.Build;

/// <summary>
/// Generates an esbuild plugin file that intercepts .jazor and .vue files.
/// </summary>
internal sealed class EsbuildPluginGenerator
{
    private readonly BuildContext _context;

    public EsbuildPluginGenerator(BuildContext context)
    {
        _context = context ?? throw new ArgumentNullException(nameof(context));
    }

    /// <summary>
    /// Generates the esbuild plugin file asynchronously.
    /// </summary>
    /// <returns>The path to the generated plugin file.</returns>
    public async Task<string> GenerateAsync()
    {
        var pluginPath = Path.Combine(_context.RootDirectory, ".jazor", "build-plugin.mjs");
        var pluginContent = GeneratePluginContent();

        // Ensure directory exists
        var directory = Path.GetDirectoryName(pluginPath);
        if (!string.IsNullOrEmpty(directory) && !Directory.Exists(directory))
        {
            Directory.CreateDirectory(directory);
        }

        await File.WriteAllTextAsync(pluginPath, pluginContent);
        return pluginPath;
    }

    /// <summary>
    /// Generates the plugin JavaScript content.
    /// </summary>
    private string GeneratePluginContent()
    {
        var serverUrl = $"http://localhost:{_context.BuildServerPort}";

        return $$"""
            // Generated by Jazor VueHost - Do not edit manually
            const BUILD_SERVER_URL = "{{serverUrl}}";

            /**
             * Compiles a file by calling the build server.
             * @param {string} path - The absolute path to the file.
             * @param {string} resolveDir - The resolve directory for the file.
             * @returns {Promise<{ contents: string, loader: string, resolveDir?: string, errors?: Array<{text: string}> }>}
             */
            async function compileFile(path, resolveDir) {
              try {
                const response = await fetch(`${BUILD_SERVER_URL}/compile`, {
                  method: 'POST',
                  headers: {
                    'Content-Type': 'application/json',
                  },
                  body: JSON.stringify({
                    id: path,
                    resolveDir: resolveDir,
                    sourceMap: true,
                  }),
                });

                if (!response.ok) {
                  const error = await response.text();
                  return {
                    errors: [{ text: `Build server error: ${error}` }]
                  };
                }

                const result = await response.json();

                if (result.isError) {
                  return {
                    errors: [{ text: result.errorMessage || 'Compilation failed.' }]
                  };
                }

                return {
                  contents: result.js,
                  loader: 'js',
                  resolveDir: resolveDir,
                };
              } catch (error) {
                return {
                  errors: [{ text: `Failed to connect to build server: ${error.message}` }]
                };
              }
            }

            /**
             * Esbuild plugin for Jazor VueHost.
             * Intercepts .jazor and .vue files and compiles them using the build server.
             */
            const jazorBuildPlugin = {
              name: 'jazor-vuehost-build',

              setup(build) {
                // Intercept .jazor files
                build.onLoad({ filter: /\.jazor$/ }, async (args) => {
                  return await compileFile(args.path, args.resolveDir);
                });

                // Intercept .vue files
                build.onLoad({ filter: /\.vue$/ }, async (args) => {
                  return await compileFile(args.path, args.resolveDir);
                });
              },
            };

            export default jazorBuildPlugin;
            """;
    }
}
