    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static productionContext =>
        {
            productionContext.AddSource(
                "Jazor.Generated.JazorVueAnalysisSupport.g.cs",
                SourceText.From(BuildAnalysisSupportSource(), Encoding.UTF8));
        });

        var documents = context.AdditionalTextsProvider
            .Where(static text => text.Path.EndsWith(".jazor", StringComparison.OrdinalIgnoreCase))
            .Select(static (text, cancellationToken) => CompileDocument(text, cancellationToken))
            .Where(static artifact => artifact is not null);

        context.RegisterSourceOutput(documents, static (productionContext, artifact) =>
        {
            if (artifact is null)
                return;

            productionContext.AddSource(
                CreateExternalDeclarationsHintName(artifact),
                SourceText.From(artifact.ExternalDeclarationsText, Encoding.UTF8));
            productionContext.AddSource(
                CreateAnalysisHintName(artifact),
                SourceText.From(artifact.AnalysisText, Encoding.UTF8));
        });

        context.RegisterSourceOutput(documents.Collect(), static (productionContext, artifacts) =>
        {
            if (artifacts.IsDefaultOrEmpty)
                return;

            productionContext.AddSource(
                "Jazor.Generated.VueArtifacts.g.cs",
                SourceText.From(BuildArtifactsSource(artifacts!), Encoding.UTF8));
        });
    }

    private static GeneratedArtifact? CompileDocument(AdditionalText text, CancellationToken cancellationToken)
    {
        var sourceText = text.GetText(cancellationToken)?.ToString();
        if (string.IsNullOrWhiteSpace(sourceText))
            return null;

        var parser = new JazorVueParser();
        var compiler = new JazorVueCompiler();
        var document = parser.Parse(text.Path, sourceText!);
        var result = compiler.Compile(document);
        return new GeneratedArtifact(
            Path.GetFileNameWithoutExtension(text.Path),
            text.Path,
            result.GeneratedVueText,
            result.GeneratedExternalDeclarationsText,
            BuildAnalysisSource(document, result.ExternalSymbols),
            CreateGeneratedImportInfos(document, result.ExternalSymbols));
    }

    private static string BuildArtifactsSource(IReadOnlyList<GeneratedArtifact?> artifacts)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("namespace Jazor.Generated");
        builder.AppendLine("{");
        builder.AppendLine("    [global::System.Runtime.CompilerServices.CompilerGenerated]");
        builder.AppendLine("    public static partial class JazorVueArtifacts");
        builder.AppendLine("    {");
        builder.AppendLine("        public static global::System.Collections.Generic.IReadOnlyList<(string Name, string VueText)> GetArtifacts()");
        builder.AppendLine("        {");
        builder.AppendLine("            return new (string Name, string VueText)[]");
        builder.AppendLine("            {");

        foreach (var artifact in artifacts.Where(static item => item is not null))
        {
            builder.Append("                (")
                .Append(EscapeCSharpString(artifact!.Name))
                .Append(", ")
                .Append(EscapeCSharpString(artifact.VueText))
                .AppendLine("),");
        }

        builder.AppendLine("            };");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        public static global::System.Collections.Generic.IReadOnlyList<(string Name, string ExternalDeclarationsText)> GetExternalDeclarations()");
        builder.AppendLine("        {");
        builder.AppendLine("            return new (string Name, string ExternalDeclarationsText)[]");
        builder.AppendLine("            {");

        foreach (var artifact in artifacts.Where(static item => item is not null))
        {
            builder.Append("                (")
                .Append(EscapeCSharpString(artifact!.Name))
                .Append(", ")
                .Append(EscapeCSharpString(artifact.ExternalDeclarationsText))
                .AppendLine("),");
        }

        builder.AppendLine("            };");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        public static global::System.Collections.Generic.IReadOnlyList<(string Name, global::System.Collections.Generic.IReadOnlyList<global::Jazor.Vue.Generated.Analysis.JazorVueImportBindingInfo> Imports)> GetImportInfos()");
        builder.AppendLine("        {");
        builder.AppendLine("            return new (string Name, global::System.Collections.Generic.IReadOnlyList<global::Jazor.Vue.Generated.Analysis.JazorVueImportBindingInfo> Imports)[]");
        builder.AppendLine("            {");

        foreach (var artifact in artifacts.Where(static item => item is not null))
        {
            builder.Append("                (")
                .Append(EscapeCSharpString(artifact!.Name))
                .Append(", ")
                .Append(BuildImportInfoArrayLiteral(artifact.ImportInfos))
                .AppendLine("),");
        }

        builder.AppendLine("            };");
        builder.AppendLine("        }");
        builder.AppendLine("    }");
        builder.AppendLine("}");
        return builder.ToString();
    }

