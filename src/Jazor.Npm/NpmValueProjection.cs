using System.Globalization;
using System.Text;
using System.Security.Cryptography;
using System.Text.Json;
using System.Text.Json.Nodes;
using Acornima;
using Acornima.Ast;
using Jazor.Compiler;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Operations;

namespace Jazor.Npm;

internal sealed class NpmValueProjection
{
    private const string FilePath = "__JoltNpmValues.g.cs";
    internal const string PackageDependencyMetadataPrefix = "Jazor.Npm.PackageDependency:";
    // npm package and subpath namespaces are always rooted at Npm.
    private const string SharedNamespace = "Jolt.Generated.Npm";
    private const string Runtime = "[global::ECMAScript.ECMAScript]";
    private const string OptionalRead = "[global::ECMAScript.ECMAScriptOptional]";
    private const string PropertyPathPrefix = "[global::ECMAScript.ECMAScriptPropertyPath";
    private readonly StringBuilder _code = new("// <auto-generated/>\n#nullable enable\n");
    private readonly Dictionary<int, (NpmValueExport? Export, NpmDefinition? Definition)> _declarations = [];
    internal bool HasPropertyPaths { get; private set; }

    internal NpmValueProjection(IEnumerable<string> namespaces, IReadOnlyList<NpmValueExport> exports, CSharpParseOptions parseOptions,
        bool standalone = false, Func<NpmDefinition, string?>? declarationLink = null)
    {
        if (standalone)
        {
            WriteLine("#pragma warning disable CS0626 // Extern members are implemented by their ECMAScript module.");
            WriteLine("#pragma warning disable CS8618 // Optional input properties may be omitted from the JS object.");
            WriteLine("#pragma warning disable CS1573, CS1712 // Upstream declarations can document only some parameters.");
            // Emit reads these exact restored dependencies from the producer DLL once catalog imports
            // establish which package specifiers are used by the application.
            foreach (var (specifier, package, version) in exports.Select(value => (value.ModuleSpecifier, value.PackageName, value.Version))
                         .Distinct().OrderBy(value => value.ModuleSpecifier, StringComparer.Ordinal)
                         .ThenBy(value => value.PackageName, StringComparer.Ordinal).ThenBy(value => value.Version, StringComparer.Ordinal))
            {
                var declaredName = specifier.Split('/').Take(specifier.StartsWith('@') ? 2 : 1);
                var dependency = string.Join('/', declaredName) == package ? version : $"npm:{package}@{version}";
                WriteLine($"[assembly: global::System.Reflection.AssemblyMetadata({SymbolDisplay.FormatLiteral(PackageDependencyMetadataPrefix + specifier, true)}, {SymbolDisplay.FormatLiteral(dependency, true)})]");
            }
        }
        var modules = exports.OrderBy(export => export.ModuleSpecifier, StringComparer.Ordinal)
            .ThenBy(export => export.ExportName, StringComparer.Ordinal).GroupBy(export => NpmNames.NamespaceFor(export.ModuleSpecifier))
            .ToDictionary(group => group.Key, group => group.ToArray(), StringComparer.Ordinal);
        var declarations = modules.ToDictionary(pair => pair.Key, pair => new ShapeDeclarations(pair.Value), StringComparer.Ordinal);
        var owners = declarations.OrderBy(pair => pair.Key, StringComparer.Ordinal)
            .SelectMany(pair => pair.Value.Handles.Select(handle => (Namespace: pair.Key, handle.Key, handle.Value)))
            .Select(handle => (handle.Namespace, handle.Key, handle.Value,
                Identity: handle.Key.SharedIdentity))
            .Where(handle => handle.Identity is not null)
            .GroupBy(handle => (handle.Identity, handle.Value.Name, handle.Key.Kind, handle.Key.Protocol));
        var shared = new ShapeDeclarations([]);
        declarations.Add(SharedNamespace, shared);
        foreach (var group in owners)
        {
            var owner = group.FirstOrDefault(handle => handle.Value.Members is { Count: > 0 });
            if (owner.Namespace is null)
                owner = group.First();
            shared.Collect(owner.Value);
            var name = shared.Add(owner.Value.Name!, owner.Value, input: false);
            var reference = $"global::{SharedNamespace}.Exports.{name}";
            foreach (var entry in group)
                declarations[entry.Namespace].ReferenceHandle(entry.Key, reference);
        }
        var emittedNamespaces = namespaces.Concat(modules.Keys);
        if (shared.HasPending)
            emittedNamespaces = emittedNamespaces.Append(SharedNamespace);
        foreach (var ns in emittedNamespaces.Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal))
        {
            // Independently generated files can contribute distinct shared types.
            // Each nested host type carries its own ECMAScript attribute.
            var container = standalone && ns == SharedNamespace ? "public static partial class" : $"{Runtime} public static class";
            WriteLine($"namespace {ns} {{ {container} Exports {{");
            var moduleExports = modules.GetValueOrDefault(ns) ?? [];
            var shapes = declarations.GetValueOrDefault(ns) ?? new ShapeDeclarations(moduleExports);
            var exportNames = moduleExports.Select(export => NpmNames.ValueNameFor(export.ExportName))
                .Select(NormalizeIdentifier).ToHashSet(StringComparer.Ordinal);
            foreach (var export in moduleExports.OrderBy(value => value.ExportName, StringComparer.Ordinal))
            {
                var name = NpmNames.ValueNameFor(export.ExportName);
                void DeclareExport(string declaration, NpmDefinition? definition, bool optional,
                    NpmValueSignature? signature = null, int? overloadPriority = null)
                {
                    WriteDocumentation(definition, signature, link: definition is null ? null : declarationLink?.Invoke(definition),
                        fallback: export.Definition);

                    if (overloadPriority is { } priority)
                        WriteLine($"[global::System.Runtime.CompilerServices.OverloadResolutionPriority({priority})]");

                    var inline = signature?.Parameters.Any(parameter => parameter.FixedUndefined) == true;
                    if (standalone || inline)
                    {
                        WriteLine($"[global::ECMAScript.ECMAScript({SymbolDisplay.FormatLiteral(export.ModuleSpecifier, true)})]");
                        WriteLine($"[global::ECMAScript.ECMAScriptName({SymbolDisplay.FormatLiteral(export.ExportName, true)})]");
                    }
                    if (optional)
                        WriteLine(OptionalRead);
                    if (inline)
                    {
                        // The shorter C# overload owns the omitted JS slot. Keep the actual call
                        // in the import's inline expression so the same contract survives a DLL.
                        var index = 0;
                        var arguments = signature!.Parameters.Select(parameter =>
                            parameter.FixedUndefined ? "void 0" :
                            parameter.FixedBoolean is { } value ? (value ? "true" : "false") :
                            $"__arg{++index}");
                        var callee = JsonSerializer.Serialize(export.ExportName);
                        var template = $"{callee}({string.Join(", ", arguments)})";
                        WriteLine($"[global::ECMAScript.ECMAScriptInline({SymbolDisplay.FormatLiteral(template, true)})]");
                    }
                    else if (signature is not null)
                        for (var index = 0; index < signature.Parameters.Count; index++)
                            if (signature.Parameters[index].FixedBoolean is { } value)
                                WriteLine($"[global::ECMAScript.ECMAScriptFixedBooleanArgument({index}, {(value ? "true" : "false")})]");
                    Declare(declaration, export, definition);
                }
                if (export.ConstantType is { } constant)
                    DeclareExport($"public static extern {Type(constant, name + "Result", shapes, input: false)} {Identifier(name)} {{ get; }}", export.Definition, constant.Kind == "undefinedable");
                if (export.AttachedMemberType is { } attached)
                {
                    // The companion reads the same import, preserving the receiver of attached methods.
                    var companion = shapes.AttachedMemberNames[export];
                    DeclareExport($"public static extern {Type(attached, companion + "View", shapes, input: false)} {Identifier(companion)} {{ get; }}",
                        export.Definition, optional: false);
                }
                var resultOverloads = new List<((string Name, int Arity, string Types) Key, string Declaration, NpmDefinition? Definition, bool Optional, NpmValueSignature Signature)>();
                foreach (var (signature, suffix) in export.Signatures.SelectMany(ScalarResultSignatures))
                {
                    var managedName = name + signature.ManagedNameSuffix;
                    // Different npm specifiers can share this C# facade.
                    if (signature.ManagedNameSuffix is not null && exportNames.Contains(NormalizeIdentifier(managedName)))
                        continue;
                    var result = Type(signature.ReturnType, name + suffix + "Result", shapes, input: false);
                    var parameters = Parameters(signature, name + suffix, shapes, input: true);
                    var optional = signature.ReturnType.Kind == "undefinedable";
                    DeclareExport($"public static extern {result} {Identifier(managedName)}{Generic(signature.TypeParameters)}({parameters}){Constraints(signature)};",
                        signature.Definition ?? export.Definition, optional, signature, signature.OverloadPriority);
                    foreach (var (index, output) in shapes.ResultArguments(signature))
                    {
                        var resultParameters = Parameters(signature, name + suffix, shapes, input: true,
                            resultArgument: (index, output));
                        var parameterTypes = string.Join(",", signature.Parameters.Select((parameter, parameterIndex) =>
                            parameterIndex == index ? output : parameter.FixedBoolean is not null || parameter.FixedUndefined ? null :
                            Type(parameter.Type, name + suffix + NpmNames.ValueNameFor(parameter.Name) + "Input", shapes, input: true))
                            .Where(type => type is not null));
                        resultOverloads.Add(((managedName, signature.TypeParameters?.Count ?? 0, parameterTypes),
                            $"public static extern {result} {Identifier(managedName)}{Generic(signature.TypeParameters)}({resultParameters}){Constraints(signature)};",
                            signature.Definition ?? export.Definition, optional, signature));
                    }
                }
                foreach (var overloads in resultOverloads.GroupBy(overload => overload.Key))
                {
                    var overload = overloads.First();
                    if (overloads.Any(other => other.Declaration != overload.Declaration || other.Optional != overload.Optional))
                        continue;
                    // Keep target-typed new() bound to the constructible input.
                    DeclareExport(overload.Declaration, overload.Definition, overload.Optional, overload.Signature, overloadPriority: -1);
                }
            }

            while (shapes.TryDequeue(out var declaration))
            {
                var (name, shape, input) = declaration;
                if (shape.Kind == "numberLiterals")
                {
                    // C# implicitly converts a bare zero to any enum. A sealed host
                    // carrier keeps the domain closed while the getters erase to numbers.
                    WriteDocumentation(shape.TypeDefinition);
                    WriteLine($"{Runtime} public sealed class {name} {{ private {name}() {{ }}");
                    foreach (var number in OrderedNumberLiterals(shape))
                    {
                        var literal = FormatNumberLiteral(number);
                        var memberName = "Value" + literal.Replace("-", "Minus", StringComparison.Ordinal)
                            .Replace("+", "Plus", StringComparison.Ordinal).Replace('.', '_');
                        if (memberName == name)
                            memberName += "_";
                        var inline = SymbolDisplay.FormatLiteral(literal, true);
                        WriteLine($"public static extern {name} {memberName} {{ [global::ECMAScript.ECMAScriptInline({inline})] get; }}");
                    }
                    WriteLine("}");
                    continue;
                }
                if (shape.Kind is "stringEnum" or "enum")
                {
                    WriteDocumentation(shape.TypeDefinition);
                    if (shape.Kind == "stringEnum")
                        _code.Append("[global::ECMAScript.StringAttribute] ");
                    WriteLine($"public enum {name} {{");
                    var used = new HashSet<string>(StringComparer.Ordinal) { name, "value__" };
                    var literalNames = (shape.StringLiterals ?? []).Select(NpmNames.ValueNameFor)
                        .Where(SyntaxFacts.IsValidIdentifier).ToHashSet(StringComparer.Ordinal);
                    string MemberName(string source)
                    {
                        var stem = NpmNames.ValueNameFor(source);
                        var fallback = !SyntaxFacts.IsValidIdentifier(stem);
                        if (fallback)
                            stem = shape.Kind == "stringEnum" ? StringEnumMemberStem(source) : "Value";
                        var field = stem;
                        // A synthesized name must leave existing identifiers available.
                        for (var suffix = 2; (fallback && literalNames.Contains(field)) || !used.Add(field); suffix++)
                            field = stem + "_" + suffix;
                        return Identifier(field);
                    }
                    // Both source identifier collisions and punctuation in a wire
                    // literal affect C# naming only. Preserve the original value.
                    foreach (var literal in shape.StringLiterals ?? [])
                        WriteLine($"[global::ECMAScript.ECMAScriptName({SymbolDisplay.FormatLiteral(literal, true)})] {MemberName(literal)},");
                    foreach (var member in shape.EnumMembers ?? [])
                        WriteLine($"{MemberName(member.Name)} = {member.Value.ToString(System.Globalization.CultureInfo.InvariantCulture)},");
                    WriteLine("}");
                    continue;
                }
                if (shape.Kind == "inputArray")
                {
                    var element = Type(shape.ElementType!, name, shapes, input: true);
                    WriteDocumentation(shape.TypeDefinition);
                    WriteLine($"{Runtime} public sealed class {name} {{ private {name}() {{ }}");
                    WriteLine($"[global::ECMAScript.ECMAScriptInline(\"__arg1.slice()\")] public static extern {name} From({element}[] values); }}");
                    continue;
                }
                var generic = shape.TypeParameters ?? TypeParameters(shape);
                var typeName = name + Generic(generic);
                var constraints = Constraints((shape.Kind == "namedRecord" || NominalKey.IsNamedRef(shape) ? null : shape.TypeParameters) ??
                    ReferenceParameters(shape).Distinct(StringComparer.Ordinal).ToArray(),
                    Collect(shape, "recordTypeParameter"), shape.ValueTypeParameters);
                if (shape.Kind == "formPathMap")
                {
                    var form = Type(shape.TypeArguments!.Single(), name + "Form", shapes, input: true);
                    var value = Type(shape.ElementType!, name + "Value", shapes, input: true);
                    var path = (shape.VeeValidatePath, shape.ArrayIndices) switch
                    {
                        (true, true) => "(VeeValidatePath = true, ArrayIndices = true)",
                        (true, false) => "(VeeValidatePath = true)",
                        (false, true) => "(ArrayIndices = true)",
                        _ => "",
                    };
                    WriteDocumentation(shape.TypeDefinition, typeParameters: generic);
                    Declare($"public sealed record {typeName} : global::System.Collections.IEnumerable{constraints} {{", null, shape.TypeDefinition);
                    // C# collection initializers require IEnumerable. The JavaScript payload is a plain object.
                    WriteLine("global::System.Collections.IEnumerator global::System.Collections.IEnumerable.GetEnumerator() => throw new global::System.NotSupportedException();");
                    // Define a flat own key, even when its spelling is special on Object.prototype.
                    if (shape.ElementType!.Kind == "undefinedable")
                        value = OptionalRead + " " + value;
                    const string write = "[global::ECMAScript.ECMAScriptInline(\"Object.defineProperty(__arg1, __arg2, { value: __arg3, writable: true, enumerable: true, configurable: true })\")]";
                    WriteLine(write);
                    WriteLine($"public extern {typeName} Set<TField>({PropertyPathPrefix}{path}] global::System.Func<{form}, TField> field, {value} value);");
                    WriteLine(write);
                    WriteLine($"public extern void Add<TField>({PropertyPathPrefix}{path}] global::System.Func<{form}, TField> field, {value} value);");
                    WriteLine("}");
                    continue;
                }
                if (shape.Kind == "union")
                {
                    // A native array branch prevents the host array's broad Array conversion
                    // from admitting values outside this closed upstream input domain.
                    var branches = shape.Variants!;
                    var variants = branches.Select(variant => variant.Kind == "array"
                        ? Type(variant.ElementType!, name, shapes, input) + "[]"
                        : Type(variant, variant.Kind == "inputDictionary" ? UnionBranchName(variant) : name, shapes, input));
                    _code.Append($"{Runtime} public readonly union {name}({string.Join(", ", variants)})");
                    if (branches.Any(variant => variant.Kind == "number"))
                    {
                        // C# cannot chain Number -> double with the union's branch conversion.
                        WriteLine($" {{ public static implicit operator {name}(global::ECMAScript.Number value) => (double)value; }}");
                    }
                    else
                        WriteLine(";");
                    continue;
                }
                if (shape.Kind == "stringArrayMapUnion")
                {
                    const string map = "global::ECMAScript.Vue.VueDictionary<string[]>";
                    WriteLine($"{Runtime} public readonly union {name}(string, string[], {map}, global::ECMAScript.False) {{");
                    WriteLine("public extern bool IsDisabled { [global::ECMAScript.ECMAScriptInline(\"__arg1 === false\")] get; }");
                    WriteLine("public extern string? AsString { [global::ECMAScript.ECMAScriptInline(\"(value => typeof value === 'string' ? value : null)(__arg1)\")] get; }");
                    WriteLine("public extern string[]? AsArray { [global::ECMAScript.ECMAScriptInline(\"(value => Array.isArray(value) ? value : null)(__arg1)\")] get; }");
                    // The closed value domain has exactly one non-array object branch. Track
                    // missing keys through Vue proxies and expose only the map's own entries.
                    WriteLine("[global::ECMAScript.ECMAScriptInline(\"((value, key) => typeof value === 'object' && value !== null && !Array.isArray(value) && key in value && Object.hasOwn(value, key) ? value[key] : null)(__arg1, __arg2)\")] public extern string[]? Get(string key);");
                    WriteLine("}");
                    continue;
                }
                if (shape.Kind == "function")
                {
                    var signature = shape.Signatures!.Single();
                    // A callback reverses which side supplies its arguments. Its return
                    // value still flows in the same direction as the callback itself.
                    WriteDocumentation(signature.Definition, signature, generic, fallback: shape.TypeDefinition);
                    WriteLine($"{Runtime} public delegate {Type(signature.ReturnType, name + "Result", shapes, input)} {typeName}({Parameters(signature, name, shapes, !input)}){constraints};");
                    continue;
                }
                if (shape.Kind == "inputDictionary")
                {
                    var element = Type(shape.ElementType!, name, shapes, input: true);
                    WriteLine($"{Runtime} public sealed record {typeName}{constraints} {{");
                    WriteLine($"public extern {element} this[string key] {{ [global::ECMAScript.ECMAScriptInline(\"__arg1[__arg2] = __arg3\")] set; }}");
                    WriteLine("}");
                    continue;
                }
                if (shape.Kind is "readonlyDictionary" or "writableDictionary")
                {
                    var element = Type(shape.ElementType!, name, shapes, input: false);
                    WriteLine($"{Runtime} public sealed class {typeName}{constraints} {{ private {name}() {{ }}");
                    var read = shape.ElementType!.Kind == "typeParameter"
                        ? $"global::ECMAScript.NullableValue<{element}>?" : Nullable(element);
                    // Vue's proxy tracks the `in` check even for keys that do not exist yet.
                    WriteLine($"[global::ECMAScript.ECMAScriptOptional] public extern {read} this[string key] {{ [global::ECMAScript.ECMAScriptInline(\"((target, key) => key in target && Object.hasOwn(target, key) ? target[key] ?? null : null)(__arg1, __arg2)\")] get; }}");
                    if (shape.Kind == "writableDictionary")
                    {
                        // A C# indexer shares one type between accessors. Set keeps the
                        // upstream write domain distinct from the nullable sparse read.
                        WriteLine($"[global::ECMAScript.ECMAScriptInline(\"__arg1[__arg2] = __arg3\")] public extern void Set(string key, {element} value);");
                        WriteLine("[global::ECMAScript.ECMAScriptInline(\"delete __arg1[__arg2]\")] public extern bool Delete(string key);");
                    }
                    WriteLine("}");
                    continue;
                }

                var constructible = shape.Kind != "enrichedRef" && (input || shape.Kind == "namedRecord");
                WriteDocumentation(shape.TypeDefinition, typeParameters: generic);
                if (constructible)
                    Declare($"public sealed record {typeName}{constraints} {{", null, shape.TypeDefinition);
                else
                {
                    WriteLine(Runtime);
                    var baseType = shape.Kind == "vuePlugin" ? " : global::ECMAScript.Vue.IVuePlugin" : "";
                    if (shape.Kind == "enrichedRef")
                    {
                        var read = Type(shape.ElementType!, name + "Value", shapes, input: false);
                        if (shape.WriteType is { } write)
                        {
                            var carrier = shape.ReadOnly ? "IVueSplitRef" : "IVueWritableRef";
                            baseType = $" : global::ECMAScript.Vue.{carrier}<{read}, {Type(write, name + "Write", shapes, input: true)}>";
                        }
                        else
                        {
                            var carrier = shape.ReadOnly ? "VueReadonlyRef" : "IVueRef";
                            baseType = $" : global::ECMAScript.Vue.{carrier}<{read}>";
                        }
                    }
                    Declare($"public sealed class {typeName}{baseType}{constraints} {{ private {name}() {{ }}", null, shape.TypeDefinition);
                }
                if (shape.Kind == "callableHandle")
                {
                    var signature = shape.Signatures!.Single();
                    var arguments = Enumerable.Range(1, signature.Parameters.Count).Select(index => $"__arg{index + 1}");
                    // The erased receiver is the JavaScript function itself.
                    var template = $"__arg1({string.Join(", ", arguments)})";
                    WriteDocumentation(signature.Definition, signature);
                    WriteLine($"[global::ECMAScript.ECMAScriptInline({SymbolDisplay.FormatLiteral(template, true)})]");
                    if (signature.ReturnType.Kind == "undefinedable")
                        WriteLine(OptionalRead);
                    WriteLine($"public extern {Type(signature.ReturnType, name + "InvokeResult", shapes, input: false)} Invoke({Parameters(signature, name + "Invoke", shapes, input: true)});");
                }
                var memberIndex = 0;
                var members = shape.Members ?? [];
                if (shape.Kind == "enrichedRef")
                {
                    var read = Type(shape.ElementType!, name + "Value", shapes, input: false);
                    if (!shape.ReadOnly || shape.WriteType is not null)
                    {
                        var setter = shape.ReadOnly ? "" : " set;";
                        WriteLine("[global::System.ComponentModel.Description(\"@#value\")]");
                        Declare($"public extern {read} Value {{ get;{setter} }}", null, shape.TypeDefinition);
                    }
                    if (shape.WriteType is { } write)
                    {
                        var writeType = Type(write, name + "Write", shapes, input: true);
                        WriteLine("[global::System.ComponentModel.Description(\"@#value\")]");
                        Declare($"public extern {writeType} WriteValue {{ set; }}", null, shape.TypeDefinition);
                    }
                }
                var reservedMembers = new HashSet<string>(StringComparer.Ordinal) { name };
                if (shape.Kind == "enrichedRef")
                    reservedMembers.UnionWith(["Value", "WriteValue"]);
                if (constructible)
                    reservedMembers.Add("Clone");
                if (shape.Kind == "callableHandle")
                    reservedMembers.Add("Invoke");
                if (shape.Kind == "tupleView")
                    reservedMembers.Add("Deconstruct");
                var usedNames = new HashSet<string>(reservedMembers, StringComparer.Ordinal);
                var authoredNames = members.Select(member => NormalizeIdentifier(NpmNames.ValueNameFor(member.Name))).ToArray();
                var unavailableNames = new HashSet<string>(authoredNames, StringComparer.Ordinal);
                unavailableNames.UnionWith(reservedMembers);
                // Keep available authored names before allocating aliases and presence helpers.
                var memberNames = new string[members.Count];
                foreach (var index in Enumerable.Range(0, members.Count).OrderBy(index => members[index].StaticKey is not null))
                {
                    var authoredName = authoredNames[index];
                    memberNames[index] = usedNames.Add(authoredName)
                        ? authoredName : ReserveMemberName(authoredName + "Value", unavailableNames);
                }
                for (var index = 0; index < members.Count; index++)
                {
                    var member = members[index];
                    var property = memberNames[index];
                    var jsName = member.JsName ?? member.Name;
                    var attribute = $"[global::System.ComponentModel.Description({SymbolDisplay.FormatLiteral("@#" + jsName, true)})]";
                    if (input && member.FixedBoolean is { } fixedValue)
                    {
                        WriteDocumentation(member.Definition);
                        WriteLine(attribute);
                        WriteLine($"[global::ECMAScript.ECMAScriptFixedBoolean({(fixedValue ? "true" : "false")})]");
                        Declare($"public bool {Identifier(property)} => {(fixedValue ? "true" : "false")};", null, member.Definition);
                        continue;
                    }
                    if (member.Type.Kind == "method")
                    {
                        foreach (var signature in member.Type.Signatures!)
                        {
                            var result = Type(signature.ReturnType, name + property + "Result", shapes, input: false);
                            WriteDocumentation(signature.Definition, signature, fallback: member.Definition);
                            if (member.StaticKey is { } staticKey)
                            {
                                // A bracketed member call keeps the original receiver and escapes JS keys independently of C#.
                                var arguments = Enumerable.Range(2, signature.Parameters.Count).Select(index => $"__arg{index}");
                                if (member.StaticListArity is { } listArity)
                                    arguments = arguments.Skip(listArity).Prepend($"[{string.Join(", ", arguments.Take(listArity))}]");
                                var wireArguments = arguments.Prepend(JsonSerializer.Serialize(staticKey));
                                var template = $"__arg1[{JsonSerializer.Serialize(jsName)}]({string.Join(", ", wireArguments)})";
                                WriteLine($"[global::ECMAScript.ECMAScriptInline({SymbolDisplay.FormatLiteral(template, true)})]");
                            }
                            else
                                WriteLine(attribute);
                            if (signature.OverloadPriority is { } priority)
                                WriteLine($"[global::System.Runtime.CompilerServices.OverloadResolutionPriority({priority})]");
                            if (signature.ReturnType.Kind == "undefinedable")
                                WriteLine(OptionalRead);
                            Declare($"public extern {result} {Identifier(property)}{Generic(signature.TypeParameters)}({Parameters(signature, name + property, shapes, input: true)}){Constraints(signature)};", null, signature.Definition ?? member.Definition);
                        }
                        continue;
                    }
                    var type = Type(member.Type, name + property + (input ? "Input" : "Member"), shapes, input);
                    if (member.Type.Kind == "optionalSlot")
                    {
                        // Absence belongs to the record, including when T is a value type.
                        // An initialized property may still contain null when T itself admits it.
                        var presence = ReserveMemberName("Has" + property, unavailableNames);
                        var ownKey = $"Object.hasOwn(__arg1, {SymbolDisplay.FormatLiteral(member.Name, true)})";
                        var inline = $"[global::ECMAScript.ECMAScriptInline({SymbolDisplay.FormatLiteral(ownKey, true)})]";
                        Declare($"public extern bool {Identifier(presence)} {{ {inline} get; }}", null, member.Definition);
                        WriteDocumentation(member.Definition);
                        WriteLine(attribute);
                        WriteLine("[global::ECMAScript.ECMAScriptRequiredRead, global::ECMAScript.ECMAScriptExplicitNull]");
                        var setter = constructible && (member.ReadOnly || shape.Kind != "namedRecord") ? " init;" :
                            member.ReadOnly ? "" : " set;";
                        Declare($"public {(constructible ? "" : "extern ")}{type} {Identifier(property)} {{ get;{setter} }}", null, member.Definition);
                        continue;
                    }
                    if (shape.Kind == "tupleView")
                    {
                        var inline = $"[global::ECMAScript.ECMAScriptInline(\"__arg1[{memberIndex++}]\")]";
                        WriteDocumentation(member.Definition);
                        Declare($"public extern {type} {Identifier(property)} {{ {inline} get; }}", null, member.Definition);
                        continue;
                    }
                    if (!input && member.Optional)
                        type = Nullable(type);
                    // C# exposes one property type. An optional getter needs a nullable
                    // result, but its setter can accept null only when TS admits null.
                    var accessors = constructible ? shape.Kind == "namedRecord" && !member.ReadOnly ? "get; set;" : "get; init;" :
                        member.ReadOnly || member.Optional && member.Type.Kind != "nullable" ? "get;" : "get; set;";
                    var modifier = constructible ? member.Optional ? "" : "required " : "extern ";
                    WriteDocumentation(member.Definition);
                    WriteLine(attribute);
                    if (!input && (member.Optional && member.Type.Kind != "function" || member.Type.Kind == "undefinedable"))
                        WriteLine(OptionalRead);
                    if (input && member.Type.Kind == "nullable" ||
                        constructible && member.Type.Kind == "typeParameter")
                        WriteLine("[global::ECMAScript.ECMAScriptExplicitNull]");
                    Declare($"public {modifier}{type} {Identifier(property)} {{ {accessors} }}", null, member.Definition);
                }
                if (shape.Kind == "tupleView")
                {
                    var outputs = shape.Members!.Select(member =>
                        $"out {Type(member.Type, name + member.Name + "Member", shapes, input: false)} {member.Name}");
                    WriteLine("[global::ECMAScript.ECMAScriptInline(\"__arg1\")]");
                    WriteLine($"public extern void Deconstruct({string.Join(", ", outputs)});");
                }
                WriteLine("}");
            }
            WriteLine("} }");
        }
        Tree = CSharpSyntaxTree.ParseText(_code.ToString(), parseOptions, FilePath);
    }

    internal SyntaxTree Tree { get; }

    // Roslyn symbols belong to a compilation. Persist source offsets and npm
    // identities, then bind fresh symbols for the current user's compilation.
    internal sealed record Declaration(int Start, string? Module, string? Export, int? Definition);

    internal Declaration[] GetDeclarations(IReadOnlyDictionary<NpmDefinition, int> indices) =>
        _declarations.Select(pair => new Declaration(pair.Key, pair.Value.Export?.ModuleSpecifier,
            pair.Value.Export?.ExportName, pair.Value.Definition is { } definition ? indices[definition] : null)).ToArray();

    internal NpmValueProjection(string source, Declaration[] declarations, IReadOnlyList<NpmValueExport> exports,
        IReadOnlyList<NpmDefinition> definitions, CSharpParseOptions parseOptions, CancellationToken cancellationToken)
    {
        Tree = CSharpSyntaxTree.ParseText(source, parseOptions, FilePath, cancellationToken: cancellationToken);
        HasPropertyPaths = source.Contains(PropertyPathPrefix, StringComparison.Ordinal);
        var values = exports.ToDictionary(value => (value.ModuleSpecifier, value.ExportName));
        foreach (var item in declarations)
            _declarations.Add(item.Start, (item.Module is null ? null : values[(item.Module, item.Export!)],
                item.Definition is { } index ? definitions[index] : null));
    }

    internal NpmValueLowering Bind(CSharpCompilation compilation)
    {
        var model = compilation.GetSemanticModel(Tree);
        var bindings = new Dictionary<ISymbol, NpmValueExport>(SymbolEqualityComparer.Default);
        var definitions = new Dictionary<ISymbol, NpmDefinition>(SymbolEqualityComparer.Default);
        foreach (var member in Tree.GetRoot().DescendantNodes().OfType<MemberDeclarationSyntax>())
        {
            // Property attributes are emitted on the preceding line. Bind the declaration
            // from its first modifier so metadata stays independent of Roslyn display strings.
            int start = member switch
            {
                MethodDeclarationSyntax { Modifiers.Count: > 0 } method => method.Modifiers[0].SpanStart,
                PropertyDeclarationSyntax property => property.Modifiers[0].SpanStart,
                RecordDeclarationSyntax { Modifiers.Count: > 0 } record => record.Modifiers[0].SpanStart,
                ClassDeclarationSyntax { Modifiers.Count: > 0 } type => type.Modifiers[0].SpanStart,
                _ => -1,
            };
            if (!_declarations.TryGetValue(start, out var metadata) || model.GetDeclaredSymbol(member) is not { } symbol)
                continue;
            // Inline exports already carry the import on their method symbol.
            if (metadata.Export is { } export && !symbol.GetAttributes().Any(attribute =>
                attribute.AttributeClass?.ToDisplayString() == "ECMAScript.ECMAScriptInlineAttribute"))
                bindings.Add(symbol, export);
            if (metadata.Definition is { } definition)
                definitions.Add(symbol, definition);
        }
        return new(bindings, definitions);
    }

    internal static bool IsProjected(ITypeSymbol type) =>
        type.DeclaringSyntaxReferences.Any(reference => reference.SyntaxTree.FilePath == FilePath);

    internal static bool ContainsVueRef(ITypeSymbol type) =>
        ContainsVueRef(type, new HashSet<ITypeSymbol>(SymbolEqualityComparer.Default));

    private static bool ContainsVueRef(ITypeSymbol type, HashSet<ITypeSymbol> visited)
    {
        static bool Matches(ITypeSymbol candidate, string name, int arity = 1) =>
            candidate is INamedTypeSymbol { ContainingType: { Name: "Vue" } parent } named &&
            named.Arity == arity && parent.ContainingNamespace.ToDisplayString() == "ECMAScript" && named.Name == name;

        static bool MutableRef(ITypeSymbol candidate) =>
            Matches(candidate, "IVueRef") || Matches(candidate, "VueOptionalRef") ||
            Matches(candidate, "IVueSplitRef", 2) || Matches(candidate, "IVueWritableRef", 2);
        if (MutableRef(type) || type.AllInterfaces.Any(MutableRef))
            return true;
        for (ITypeSymbol? candidate = type; candidate is not null; candidate = candidate.BaseType)
            if (Matches(candidate, "VueReadonlyRef") || Matches(candidate, "VueReadonlyOptionalRef"))
                return true;
        // Projected handle graphs can refer back to a previously visited declaration.
        if (!visited.Add(type))
            return false;
        if (type is IArrayTypeSymbol array)
            return ContainsVueRef(array.ElementType, visited);
        if (type is INamedTypeSymbol { Arity: 1, Name: "Array" or "IArray" } hostArray &&
            hostArray.ContainingNamespace.ToDisplayString() == "ECMAScript")
            return ContainsVueRef(hostArray.TypeArguments[0], visited);
        return IsProjected(type) && type.GetMembers().OfType<IPropertySymbol>().Any(property => ContainsVueRef(property.Type, visited));
    }

    // Source offsets cached for symbol binding must be identical on every platform.
    private void WriteLine(string line) => _code.Append(line).Append('\n');

    private void WriteDocumentation(NpmDefinition? definition, NpmValueSignature? signature = null,
        IReadOnlyList<string>? typeParameters = null, string? link = null, NpmDefinition? fallback = null)
    {
        var docs = definition?.Documentation ??
            (fallback is { DocumentationFromCallableOwner: true } ? fallback.Documentation : null);
        if (docs is null && link is null)
            return;

        var summary = docs?.Summary;
        if (!string.IsNullOrWhiteSpace(summary) || link is not null)
        {
            WriteLine("/// <summary>");
            if (!string.IsNullOrWhiteSpace(summary))
                WriteDocumentationLines(summary);
            if (link is not null)
                WriteLine($"""/// <see href="{XmlText(link)}">Open TypeScript declaration</see>""");
            WriteLine("/// </summary>");
        }
        if (docs is null)
            return;
        foreach (var name in typeParameters ?? signature?.TypeParameters ?? [])
            if (docs.TypeParameters?.TryGetValue(name, out var text) == true)
                Element("typeparam", text, TypeParameterIdentifier(name).TrimStart('@'));
        foreach (var parameter in signature?.Parameters ?? [])
            if (parameter.FixedBoolean is null && !parameter.FixedUndefined &&
                docs.Parameters?.TryGetValue(parameter.Name, out var text) == true)
                Element("param", text, NormalizeIdentifier(parameter.Name));
        if (signature is { ReturnType.Kind: not "void" })
            Element("returns", docs.Returns);
        var deprecated = docs.Deprecated is null ? null : string.IsNullOrWhiteSpace(docs.Deprecated)
            ? "Deprecated" : $"Deprecated: {docs.Deprecated}";
        var remarks = deprecated is null ? docs.Remarks : string.IsNullOrWhiteSpace(docs.Remarks)
            ? deprecated : $"{docs.Remarks}\n{deprecated}";
        Element("remarks", remarks);
        foreach (var example in docs.Examples ?? [])
            Element("example", example);

        void Element(string tag, string? content, string? name = null)
        {
            if (string.IsNullOrWhiteSpace(content))
                return;
            var attribute = name is null ? "" : $" name=\"{XmlText(name)}\"";
            if (!content.Contains('\n') && !content.Contains('\r'))
            {
                WriteLine($"/// <{tag}{attribute}>{XmlText(content)}</{tag}>");
                return;
            }
            WriteLine($"/// <{tag}{attribute}>");
            WriteDocumentationLines(content);
            WriteLine($"/// </{tag}>");
        }

        void WriteDocumentationLines(string content)
        {
            foreach (var line in content.ReplaceLineEndings("\n").Split('\n'))
                WriteLine("/// " + XmlText(line));
        }
    }

    private static string XmlText(string text)
    {
        var xml = new StringBuilder(text.Length);
        foreach (var character in text.EnumerateRunes())
            xml.Append(character.Value switch
            {
                '<' => "&lt;", '>' => "&gt;", '&' => "&amp;", '"' => "&quot;", '\'' => "&apos;",
                '\r' => "&#13;", '\n' => "&#10;", 0x85 => "&#133;", 0x2028 => "&#8232;", 0x2029 => "&#8233;",
                '\t' => "\t",
                >= 0x20 and <= 0xD7FF or >= 0xE000 and <= 0xFFFD or >= 0x10000 => character.ToString(),
                _ => "",
            });
        return xml.ToString();
    }

    private void Declare(string declaration, NpmValueExport? export, NpmDefinition? definition)
    {
        _declarations.Add(_code.Length, (export, definition));
        WriteLine(declaration);
    }

    private string Parameters(NpmValueSignature signature, string name, ShapeDeclarations shapes, bool input,
        (int Index, string Type)? resultArgument = null) =>
        string.Join(", ", signature.Parameters.Select((parameter, index) =>
        {
            if (parameter.FixedBoolean is not null || parameter.FixedUndefined)
                return null;
            var type = resultArgument is { } argument && argument.Index == index ? argument.Type :
                Type(parameter.Type, name + NpmNames.ValueNameFor(parameter.Name) + (input ? "Input" : "Member"), shapes, input);
            var declaration = $"{(parameter.ReadOnlyReference ? "in " : "")}{type} {Identifier(parameter.Name)}";
            if (input && parameter.Type.Kind == "undefinedable")
                declaration = $"{OptionalRead} {declaration}";
            if (parameter.OptionalCallback)
                declaration = $"[global::ECMAScript.ECMAScriptOptionalCallback] {declaration}";
            if (parameter.RestCallback)
                declaration = $"[global::ECMAScript.ECMAScriptRestCallback] {declaration}";
            if (parameter.Type.Kind is "propertyPath" or "propertyKey")
            {
                HasPropertyPaths = true;
                var mode = parameter.Type.Kind switch
                {
                    "propertyKey" when parameter.Type.RequirePlainRecord =>
                        "(singleKey: true, IndirectRead = true, RequirePlainRecord = true)",
                    "propertyKey" when parameter.Type.RequireRecordView =>
                        "(singleKey: true, IndirectRead = true, RequireRecordView = true)",
                    "propertyKey" when signature.ReturnType is { Kind: "ref", ElementType: { } read } &&
                        parameter.Type.Variants is [{ } selected] &&
                        read.Kind == selected.Kind &&
                        string.Equals(read.Name, selected.Name, StringComparison.Ordinal) => "(singleKey: true, IndirectRead = true)",
                    "propertyKey" => "(singleKey: true)",
                    _ when parameter.Type.ArrayIndices => parameter.Type.VeeValidatePath
                        ? "(VeeValidatePath = true, ArrayIndices = true)" : "(ArrayIndices = true)",
                    _ when parameter.Type.VeeValidatePath => "(VeeValidatePath = true)",
                    _ => "",
                };
                declaration = $"{PropertyPathPrefix}{mode}] {declaration}";
            }
            return parameter.Optional ? $"[global::System.Runtime.InteropServices.Optional] {declaration}" : declaration;
        }).Where(declaration => declaration is not null));

    private static string Type(NpmValueType type, string name, ShapeDeclarations shapes, bool input)
    {
        switch (type.Kind)
        {
            case "string": return "string";
            case "number": return "double";
            case "unknownValue": return "global::ECMAScript.UnknownValue";
            case "boolean": return "bool";
            case "void": return "void";
            case "date": return "global::ECMAScript.Date";
            case "error": return "global::ECMAScript.Error";
            case "plainRecord": return "global::ECMAScript.Vue.VueProps";
            case "stringArrayMapUnion": return shapes.Add(name, type, input: false);
            case "propertyPath":
            case "propertyKey":
                return $"global::System.Func<{Type(type.ElementType!, name, shapes, input)}, {Type(type.Variants!.Single(), name, shapes, input)}>";
            case "web": return $"global::ECMAScript.{type.Name}";
            case "typeParameter":
            case "recordTypeParameter": return TypeParameterIdentifier(type.Name!);
            case "optionalSlot":
                var slot = Type(type.ElementType!, name, shapes, input);
                return type.Name == "nullable" ? $"global::ECMAScript.NullableValue<{slot}>?" : slot;
            case "partialRecord":
                return $"global::ECMAScript.Vue.PartialRecord<{Type(type.ElementType!, name, shapes, input)}>";
            case "unwrappedRecord":
                return $"global::ECMAScript.Vue.VueUnwrappedRecord<{Type(type.ElementType!, name, shapes, input)}>";
            case "formPathMap":
                return shapes.Add(name, type, input: true) + Generic(TypeParameters(type));
            case "enum":
            case "stringEnum":
                var domain = type.Name is { } declared ? NpmNames.ValueNameFor(declared) : name;
                return shapes.Add(SyntaxFacts.IsValidIdentifier(domain) ? domain : name, type, input: false);
            case "numberLiterals":
                // Complete and partial write records describe the same finite
                // domain even when their generated parameter names differ.
                var numericDomain = type.Name is { } numericName ? NpmNames.ValueNameFor(numericName) : null;
                if (!SyntaxFacts.IsValidIdentifier(numericDomain))
                {
                    var identity = string.Join(",", OrderedNumberLiterals(type).Select(FormatNumberLiteral));
                    numericDomain = "NumberLiterals_" + Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(identity)))[..12];
                }
                return shapes.Add(numericDomain!, type, input: false);
            case "undefinedable":
            case "nullable": return Nullable(Type(type.ElementType!, name, shapes, input));
            case "nullableSlot":
                return $"global::ECMAScript.NullableValue<{Type(type.ElementType!, name, shapes, input)}>?";
            case "dictionary":
                return $"global::ECMAScript.Vue.VueDictionary<{Type(type.ElementType!, name, shapes, input)}>";
            case "inputDictionary":
                return shapes.Add(name, type, input: true) + Generic(TypeParameters(type));
            case "readonlyDictionary":
            case "writableDictionary":
                return shapes.Add(type.Name ?? name, type, input: false) + Generic(TypeParameters(type));
            case "array":
                // Array<T> also accepts System.Array, so it cannot enforce element
                // invariance for a mutable heterogeneous TypeScript array.
                if ((input || !type.ReadOnly) && type.ElementType!.Kind == "union")
                    return $"{Type(type.ElementType, name, shapes, input)}[]";
                return $"global::ECMAScript.{(type.ReadOnly ? "IArray" : "Array")}<{Type(type.ElementType!, name, shapes, input)}>";
            case "inputArray":
                return shapes.Add(type.ElementType!.Name + "Sequence", type, input: true);
            case "recordArray": return $"{Type(type.ElementType!, name, shapes, input: true)}[]";
            case "promise":
                return type.ElementType!.Kind == "void" ? "global::ECMAScript.IPromise" :
                    $"global::ECMAScript.IPromise<{Type(type.ElementType, name, shapes, input)}>";
            case "ref":
                if (type.WriteType is { } write)
                {
                    var carrier = type.Name switch
                    {
                        "VueWritableComputedRef" => type.ReadOnly ? "VueSplitComputedRef" : "VueWritableComputedRef",
                        "VueSplitOptionalRef" => "VueSplitOptionalRef",
                        _ => type.ReadOnly ? "IVueSplitRef" : "IVueWritableRef",
                    };
                    return $"global::ECMAScript.Vue.{carrier}<{Type(type.ElementType!, name, shapes, input: false)}, {Type(write, name + "Write", shapes, input: true)}>";
                }
                var refName = type.ReadOnly && type.ElementType!.Kind == "undefinedable"
                    ? "VueReadonlyOptionalRef" : type.Name ?? (type.ReadOnly ? "VueReadonlyRef" : "IVueRef");
                return $"global::ECMAScript.Vue.{refName}<{Type(type.ElementType!, name, shapes, input)}>";
            case "union":
                // Canonicalize the same closed element set across all call sites.
                var variants = type.Variants!.OrderBy(variant => variant.Kind, StringComparer.Ordinal).ToArray();
                var unionName = string.Join("Or", variants.Select(UnionBranchName));
                return shapes.Add(unionName, type with { Variants = variants }, input: false);
            case "vuePlugin" when type.Members is not { Count: > 0 }:
                return "global::ECMAScript.Vue.IVuePlugin";
            case "vuePlugin":
            case "handle":
            case "namedRecord":
            case "enrichedRef" when NominalKey.IsNominal(type):
                var handle = shapes.Add(name, type, input: false);
                return type.TypeArguments is { Count: > 0 } arguments
                    ? $"{handle}<{string.Join(", ", arguments.Select(argument => Type(argument, name, shapes, input)))}>"
                    : handle;
            case "function" when type.Signatures is [{ Parameters.Count: 0, ReturnType.Kind: "void" }]
                && TypeParameters(type).Length == 0:
                return "global::System.Action";
            case "action":
                return $"global::System.Action<{Type(type.Signatures!.Single().Parameters.Single().Type, name, shapes, input)}>";
            case "enrichedRef":
                return shapes.Add(name, type, input: false) + Generic(TypeParameters(type));
            case "object":
            case "tupleView":
            case "callableHandle":
            case "function":
                return shapes.Add(name, type, input) + Generic(TypeParameters(type));
            default:
                throw new InvalidOperationException($"Unsupported npm type projection '{type.Kind}'.");
        }
    }

    private static string Nullable(string type) => type.EndsWith('?') ? type : type + "?";

    private static string UnionBranchName(NpmValueType type) => type.Kind switch
    {
        "array" => UnionBranchName(type.ElementType!) + "Array",
        "dictionary" or "inputDictionary" => UnionBranchName(type.ElementType!) + "Dictionary",
        "union" => string.Join("Or", type.Variants!.Select(UnionBranchName)),
        _ => NpmNames.ValueNameFor(type.Kind),
    };

    private static IEnumerable<(NpmValueSignature Signature, string Suffix)> ScalarResultSignatures(NpmValueSignature signature)
    {
        yield return (signature, "");
        if (signature.ScalarResultTypeParameter is not { } parameter)
            yield break;

        var independent = (signature.ReferenceTypeParameters ?? [])
            .Where(name => name != parameter && ReferenceParameters(signature.ReturnType).Contains(name, StringComparer.Ordinal))
            .Distinct(StringComparer.Ordinal).ToArray();
        if (independent is [var slot] && signature.ReturnType.Kind == "object" &&
            signature.Parameters is [{ Type.Kind: "object" } options])
        {
            // Specialize the observable absence, independently of the numeric
            // carrier. A struct-constrained slot uses Nullable<T> in the result.
            var values = new[] { slot };
            var valueSignature = signature with
            {
                Parameters = [options with { Type = options.Type with { ValueTypeParameters = values } }],
                ReturnType = signature.ReturnType with { ValueTypeParameters = values },
                ValueTypeParameters = values,
            };
            yield return (valueSignature, "Value");
            yield return (Substitute(valueSignature, parameter, new("number")), "NumberValue");
            yield return (Substitute(valueSignature, parameter, new("boolean")), "BooleanValue");
        }

        // Specialize the result slot alone. Other correlated parameters, such as
        // mutation variables, remain generic and can still be inferred independently.
        // Observing an absent value of an independent open parameter would require
        // its own specialization. Keep that property on the reference overload.
        signature = signature with
        {
            ReturnType = signature.ReturnType with
            {
                Members = signature.ReturnType.Members?.Where(member => !ReferenceParameters(member.Type)
                    .Any(name => name != parameter &&
                        signature.ReferenceTypeParameters?.Contains(name, StringComparer.Ordinal) != true)).ToArray(),
            },
        };
        signature = signature with
        {
            ReferenceTypeParameters = signature.ReferenceTypeParameters?.Where(name => name == parameter ||
                signature.Parameters.Any(value => ReferenceParameters(value.Type).Contains(name, StringComparer.Ordinal)) ||
                ReferenceParameters(signature.ReturnType).Contains(name, StringComparer.Ordinal)).ToArray(),
        };
        yield return (Substitute(signature, parameter, new("number")), "Number");
        yield return (Substitute(signature, parameter, new("boolean")), "Boolean");
    }

    private static NpmValueSignature Substitute(NpmValueSignature signature, string parameter, NpmValueType replacement) =>
        signature with
        {
            TypeParameters = signature.TypeParameters?.Where(name => name != parameter).ToArray(),
            ReferenceTypeParameters = signature.ReferenceTypeParameters?.Where(name => name != parameter).ToArray(),
            Parameters = signature.Parameters.Select(value => value with { Type = Substitute(value.Type, parameter, replacement) }).ToArray(),
            ReturnType = Substitute(signature.ReturnType, parameter, replacement),
            ScalarResultTypeParameter = null,
        };

    private static NpmValueType Substitute(NpmValueType type, string parameter, NpmValueType replacement)
    {
        if (type.Kind == "typeParameter" && type.Name == parameter)
            return replacement;

        return type with
        {
            ElementType = type.ElementType is { } element ? Substitute(element, parameter, replacement) : null,
            WriteType = type.WriteType is { } write ? Substitute(write, parameter, replacement) : null,
            Members = type.Members?.Select(member => member with { Type = Substitute(member.Type, parameter, replacement) }).ToArray(),
            Signatures = type.Signatures?.Select(signature => signature.TypeParameters?.Contains(parameter, StringComparer.Ordinal) == true
                ? signature : Substitute(signature, parameter, replacement)).ToArray(),
            Variants = type.Variants?.Select(variant => Substitute(variant, parameter, replacement)).ToArray(),
            TypeArguments = type.TypeArguments?.Select(argument => Substitute(argument, parameter, replacement)).ToArray(),
        };
    }

    private static string Generic(IReadOnlyList<string>? names) =>
        names is { Count: > 0 } ? $"<{string.Join(", ", names.Select(TypeParameterIdentifier))}>" : "";

    private static string Constraints(IEnumerable<string> references, IEnumerable<string> records, IReadOnlyList<string>? values = null)
    {
        var recordNames = records.ToHashSet(StringComparer.Ordinal);
        return string.Concat(references.Except(recordNames, StringComparer.Ordinal).Except(values ?? [], StringComparer.Ordinal)
            .Select(name => $" where {TypeParameterIdentifier(name)} : class")) +
            string.Concat(recordNames.Order(StringComparer.Ordinal)
            .Select(name => $" where {TypeParameterIdentifier(name)} : global::ECMAScript.Vue.VueProps")) +
            string.Concat((values ?? []).Select(name => $" where {TypeParameterIdentifier(name)} : struct"));
    }

    private static string Constraints(NpmValueSignature signature) =>
        Constraints(ReferenceParameters(signature), Collect(signature, "recordTypeParameter")
            .Where(name => signature.TypeParameters?.Contains(name, StringComparer.Ordinal) == true)) +
        string.Concat((signature.ValueTypeParameters ?? []).Select(name => $" where {TypeParameterIdentifier(name)} : struct"));

    private static string[] ReferenceParameters(NpmValueSignature signature) =>
        (signature.ReferenceTypeParameters ?? []).Concat(ReferenceParameters(signature.ReturnType))
        .Concat(signature.Parameters.SelectMany(parameter => ReferenceParameters(parameter.Type)))
        .Where(name => signature.TypeParameters?.Contains(name, StringComparer.Ordinal) == true)
        .Where(name => signature.ValueTypeParameters?.Contains(name, StringComparer.Ordinal) != true)
        .Distinct(StringComparer.Ordinal).ToArray();

    private static IEnumerable<string> ReferenceParameters(NpmValueType type)
    {
        if (type.Kind is "undefinedable" or "nullable" && type.ElementType is { Kind: "typeParameter", Name: { } name })
            yield return name;
        if (type.Kind == "handle")
            foreach (var argument in type.TypeArguments ?? [])
                foreach (var parameter in Collect(argument))
                    yield return parameter;
        if (NominalKey.IsNamedRef(type) && type.TypeArguments is not null)
            yield break;
        if (type.ElementType is { } element)
            foreach (var parameter in ReferenceParameters(element))
                yield return parameter;
        if (type.WriteType is { } write)
            foreach (var parameter in ReferenceParameters(write))
                yield return parameter;
        if (type.Kind == "namedRecord")
            foreach (var argument in type.TypeArguments ?? [])
                foreach (var parameter in ReferenceParameters(argument))
                    yield return parameter;
        foreach (var member in type.Kind == "namedRecord" ? [] : type.Members ?? [])
            foreach (var parameter in ReferenceParameters(member.Type))
                yield return parameter;
        foreach (var signature in type.Signatures ?? [])
            foreach (var parameter in ReferenceParameters(signature.ReturnType)
                .Concat(signature.Parameters.SelectMany(parameter => ReferenceParameters(parameter.Type)))
                .Except(signature.TypeParameters ?? [], StringComparer.Ordinal))
                yield return parameter;
    }

    private static string[] TypeParameters(NpmValueType type) =>
        Collect(type).Concat(Collect(type, "recordTypeParameter")).Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal).ToArray();

    private static IEnumerable<string> Collect(NpmValueSignature signature, string kind) =>
        Collect(signature.ReturnType, kind).Concat(signature.Parameters.SelectMany(parameter => Collect(parameter.Type, kind)));

    private static IEnumerable<string> Collect(NpmValueType type, string kind = "typeParameter")
    {
        if (type.Kind == kind)
            yield return type.Name!;
        // At a use site, the alias's formals are scoped to its declaration.
        if (NominalKey.IsNamedRef(type) && type.TypeArguments is not null)
        {
            foreach (var argument in type.TypeArguments)
                foreach (var name in Collect(argument, kind))
                    yield return name;
            yield break;
        }
        if (type.ElementType is { } element)
            foreach (var name in Collect(element, kind))
                yield return name;
        if (type.WriteType is { } write)
            foreach (var name in Collect(write, kind))
                yield return name;
        foreach (var argument in type.TypeArguments ?? [])
            foreach (var name in Collect(argument, kind))
                yield return name;
        foreach (var member in type.Kind == "namedRecord" ? [] : type.Members ?? [])
            foreach (var name in Collect(member.Type, kind))
                yield return name;
        foreach (var signature in type.Signatures ?? [])
            foreach (var name in Collect(signature, kind)
                .Except(signature.TypeParameters ?? [], StringComparer.Ordinal))
                yield return name;
    }

    private static string Identifier(string name) => "@" + NormalizeIdentifier(name);

    private static string StringEnumMemberStem(string literal)
    {
        var stem = new StringBuilder();
        var wordStart = true;
        foreach (var character in literal)
        {
            if (!SyntaxFacts.IsIdentifierPartCharacter(character))
            {
                wordStart = true;
                continue;
            }
            if (stem.Length == 0 && !SyntaxFacts.IsIdentifierStartCharacter(character))
                continue;
            stem.Append(wordStart ? char.ToUpperInvariant(character) : character);
            wordStart = false;
        }
        var candidate = stem.ToString();
        return SyntaxFacts.IsValidIdentifier(candidate) ? candidate : "Value";
    }

    private static string ReserveMemberName(string stem, HashSet<string> unavailableNames)
    {
        var candidate = stem;
        for (var suffix = 2; !unavailableNames.Add(candidate); suffix++)
            candidate = stem + "_" + suffix;
        return candidate;
    }

    private static string TypeParameterIdentifier(string name)
    {
        const string escapedPrefix = "__JoltTypeParameter_";
        if (SyntaxFacts.IsIdentifierStartCharacter(name[0]) &&
            name.All(character => SyntaxFacts.IsIdentifierPartCharacter(character) &&
                char.GetUnicodeCategory(character) != System.Globalization.UnicodeCategory.Format) &&
            !name.StartsWith(escapedPrefix, StringComparison.Ordinal))
            return "@" + name;

        // C# ignores formatting characters and TypeScript permits '$' in identifiers.
        // Reserve the escape prefix so both cases keep their original slot identity.
        return "@" + escapedPrefix + string.Concat(name.Select(character => ((int)character).ToString("X4")));
    }

    private static IEnumerable<double> OrderedNumberLiterals(NpmValueType type) =>
        type.NumberLiterals!.Select(value => value == 0 ? 0d : value).Distinct().Order();

    private static string FormatNumberLiteral(double value) => value.ToString("R", CultureInfo.InvariantCulture);

    private static string NormalizeIdentifier(string name) =>
        new(name.Select(character => SyntaxFacts.IsIdentifierPartCharacter(character) ? character : '_').ToArray());

    internal static string? PackageDeclarationPath(NpmDefinition definition)
    {
        const string marker = "/node_modules/";
        var path = definition.Path.Replace('\\', '/');
        var index = path.LastIndexOf(marker, StringComparison.Ordinal);
        return index < 0 ? null : path[(index + marker.Length)..];
    }

    private readonly record struct NominalKey(NpmDefinition? Definition, string Kind, string? Protocol, string? Identity)
    {
        public string? SharedIdentity => Kind is "namedRecord" or "stringEnum" or "numberLiterals" or "enrichedRef" or "stringArrayMapUnion"
            ? Identity
            : PackageDeclarationPath(Definition!);

        public static bool IsNominal(NpmValueType type) =>
            type is { TypeDefinition: not null, Kind: "handle" or "namedRecord" } or
                { TypeDefinition: not null, Kind: "stringEnum" or "numberLiterals" or "stringArrayMapUnion", TypeIdentity: not null } ||
            IsNamedRef(type);

        public static bool IsNamedRef(NpmValueType type) =>
            type is { Kind: "enrichedRef", TypeDefinition: not null, TypeIdentity: not null };

        public static NominalKey From(NpmValueType type) =>
            type is { Kind: "namedRecord" or "stringEnum" or "numberLiterals" or "enrichedRef" or "stringArrayMapUnion", TypeIdentity: { } identity }
                ? new(null, type.Kind, type.ProtocolKey, identity)
                : new(type.TypeDefinition, type.Kind, type.ProtocolKey, null);
    }

    private sealed class ShapeDeclarations
    {
        private readonly HashSet<string> _reservedNames;
        private readonly Dictionary<string, (NpmValueType Type, bool Input)> _names = new(StringComparer.Ordinal);
        private readonly Queue<(string Name, NpmValueType Type, bool Input)> _pending = new();
        private readonly Dictionary<NominalKey, NpmValueType> _handles = [];
        private readonly Dictionary<NominalKey, string> _handleReferences = [];
        public IReadOnlyDictionary<NpmValueExport, string> AttachedMemberNames { get; }
        public IReadOnlyDictionary<NominalKey, NpmValueType> Handles => _handles;
        public void ReferenceHandle(NominalKey definition, string name) =>
            _handleReferences.Add(definition, name);
        private readonly Dictionary<(NpmDefinition? Definition, string? Identity), List<(string Name, NpmValueType Type)>> _results = [];

        private static (NpmDefinition? Definition, string? Identity) ResultKey(NpmValueType type) =>
            type.TypeIdentity is { } identity ? (null, identity) : (type.TypeDefinition, null);

        public ShapeDeclarations(IReadOnlyList<NpmValueExport> exports)
        {
            _reservedNames = new(exports.Select(export => NpmNames.ValueNameFor(export.ExportName)).Append("Exports"), StringComparer.Ordinal);
            var companionNames = new Dictionary<NpmValueExport, string>();
            var occupied = _reservedNames.Select(NormalizeIdentifier).ToHashSet(StringComparer.Ordinal);
            foreach (var export in exports)
            {
                var name = NpmNames.ValueNameFor(export.ExportName);
                foreach (var signature in export.Signatures)
                    occupied.Add(NormalizeIdentifier(name + signature.ManagedNameSuffix));
            }
            foreach (var export in exports.Where(export => export.AttachedMembers is { Count: > 0 }))
            {
                var name = NormalizeIdentifier(NpmNames.ValueNameFor(export.ExportName));
                var companion = name + (export.AttachedMemberSuffix ?? NpmExportSelection.ReserveAttachedMemberSuffix(name, occupied));
                companionNames.Add(export, companion);
                _reservedNames.Add(companion);
            }
            AttachedMemberNames = companionNames;
            foreach (var export in exports)
            {
                if (export.ConstantType is { } constant)
                    Collect(constant);
                if (export.AttachedMemberType is { } attached)
                    Collect(attached);
                var exportName = NpmNames.ValueNameFor(export.ExportName);
                foreach (var (signature, suffix) in export.Signatures.SelectMany(ScalarResultSignatures))
                {
                    CollectSignature(signature);
                    if (signature.ReturnType is { Kind: "object", TypeDefinition: not null } result)
                    {
                        var key = ResultKey(result);
                        if (!_results.TryGetValue(key, out var results))
                            _results.Add(key, results = []);
                        var resultName = exportName + suffix + "Result";
                        if (!results.Any(previous => SameType(result, previous.Type)))
                            results.Add((resultName, result));
                    }
                }
            }
        }

        public IEnumerable<(int Index, string Type)> ResultArguments(NpmValueSignature signature)
        {
            for (var index = 0; index < signature.Parameters.Count; index++)
            {
                if (signature.Parameters[index].Type is not { Kind: "object", TypeDefinition: not null } input ||
                    !_results.TryGetValue(ResultKey(input), out var results))
                    continue;
                foreach (var (name, result) in results)
                {
                    var inputArguments = input.TypeArguments ?? [];
                    var resultArguments = result.TypeArguments ?? [];
                    if (input.TypeIdentity is null)
                    {
                        if (SameSequence(inputArguments, resultArguments, SameType))
                            yield return (index, Type(result, name, this, input: false));
                        continue;
                    }

                    var substitutions = new Dictionary<string, string>(StringComparer.Ordinal);
                    var occupied = new HashSet<string>(StringComparer.Ordinal);
                    // Bind by alias argument position. A bijection preserves
                    // whether two slots refer to the same method generic.
                    bool BindParameter(string producer, string consumer)
                    {
                        if (substitutions.TryGetValue(producer, out var previous))
                            return previous == consumer;
                        if (signature.TypeParameters?.Contains(consumer, StringComparer.Ordinal) != true ||
                            !occupied.Add(consumer))
                            return false;
                        substitutions.Add(producer, consumer);
                        return true;
                    }

                    bool MatchesParameter(string producer, string consumer) =>
                        substitutions.TryGetValue(producer, out var bound) && bound == consumer;

                    if (!SameSequence(resultArguments, inputArguments, (producer, consumer) => SameType(producer, consumer, BindParameter)) ||
                        !SameSequence(result.Members ?? [], input.Members ?? [],
                            (producer, consumer) => SameMember(producer, consumer, MatchesParameter)))
                        continue;
                    var parameters = TypeParameters(result);
                    if (parameters.Any(parameter => !substitutions.ContainsKey(parameter)))
                        continue;
                    yield return (index, Add(name, result, input: false) +
                        Generic(parameters.Select(parameter => substitutions[parameter]).ToArray()));
                }
            }
        }

        private void CollectSignature(NpmValueSignature signature)
        {
            Collect(signature.ReturnType);
            foreach (var parameter in signature.Parameters)
                Collect(parameter.Type);
        }

        public void Collect(NpmValueType type)
        {
            // Recursive uses carry only the declaration identity. Look up the full
            // definition independently of the order in which export signatures emit.
            if (NominalKey.IsNominal(type))
            {
                var key = NominalKey.From(type);
                if (!_handles.ContainsKey(key) || type.Members is { Count: > 0 })
                    _handles[key] = type;
            }
            if (type.ElementType is { } element)
                Collect(element);
            if (type.WriteType is { } write)
                Collect(write);
            foreach (var variant in type.Variants ?? [])
                Collect(variant);
            foreach (var argument in type.TypeArguments ?? [])
                Collect(argument);
            foreach (var signature in type.Signatures ?? [])
                CollectSignature(signature);
            foreach (var member in type.Members ?? [])
                Collect(member.Type);
        }

        public string Add(string name, NpmValueType type, bool input)
        {
            name = NormalizeIdentifier(name);
            var nominal = NominalKey.IsNominal(type);
            if (nominal)
            {
                var key = NominalKey.From(type);
                if (_handleReferences.TryGetValue(key, out var reference))
                    return reference;
                type = _handles.GetValueOrDefault(key, type) with { TypeArguments = null };
            }
            if ((nominal || type.Kind is "object" or "stringArrayMapUnion") &&
                type is { Name: { } sourceName, TypeDefinition: not null })
            {
                var publicName = NpmNames.ValueNameFor(sourceName);
                if (type is { Kind: "object", TypeArguments.Count: > 0, TypeIdentity: null })
                    publicName += "Of" + string.Join("And", type.TypeArguments.Select(ArgumentName));
                if (type.Kind == "object" && !input)
                    publicName += "Result";
                if (SyntaxFacts.IsValidIdentifier(publicName))
                    name = nominal && NominalKey.From(type).SharedIdentity is { } path
                        ? publicName + "_" + StableDeclarationSuffix(path, sourceName, type)
                        : publicName;
            }

            for (int suffix = 1; ; suffix++)
            {
                var candidate = suffix == 1 ? name : type.Kind == "object"
                    ? name + "_" + StableDeclarationSuffix(
                        type.TypeDefinition is { } location ? PackageDeclarationPath(location) ?? "" : "",
                        type.Name ?? name, type) + (suffix == 2 ? "" : "_" + suffix)
                    : name + "_" + suffix;
                if (_reservedNames.Contains(candidate) ||
                    type.Members?.Any(member => NpmNames.ValueNameFor(member.Name) == candidate) == true)
                    continue;
                if (_names.TryGetValue(candidate, out var previous))
                {
                    // 同名选项可能来自不同声明，或在两个使用处有不同的投影形状。
                    if (previous.Input == input && SameType(previous.Type, type))
                        return candidate;
                    continue;
                }
                _names.Add(candidate, (type, input));
                _pending.Enqueue((candidate, type, input));
                return candidate;
            }
        }

        private static string StableDeclarationSuffix(string path, string name, NpmValueType type)
        {
            var identity = path + "\n" + name + "\n" + type.ProtocolKey;
            if (type.Kind is "namedRecord" or "stringEnum" or "numberLiterals" or "enrichedRef")
                identity += "\n" + type.Kind;
            // One TS record can have multiple projected use-site shapes.
            // Source spans identify definitions for navigation only.
            if (type.Kind == "object")
            {
                var shape = JsonSerializer.SerializeToNode(type)!;
                RemoveLocations(shape);
                identity += "\n" + shape.ToJsonString();
            }
            return Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(identity)))[..12];

            static void RemoveLocations(JsonNode node)
            {
                if (node is JsonObject properties)
                {
                    properties.Remove(nameof(NpmValueType.TypeDefinition));
                    properties.Remove(nameof(NpmValueMember.Definition));
                    foreach (var (_, property) in properties)
                        if (property is not null)
                            RemoveLocations(property);
                }
                else if (node is JsonArray items)
                    foreach (var item in items)
                        if (item is not null)
                            RemoveLocations(item);
            }
        }

        public bool TryDequeue(out (string Name, NpmValueType Type, bool Input) declaration) => _pending.TryDequeue(out declaration);
        public bool HasPending => _pending.Count != 0;

        private static string ArgumentName(NpmValueType argument) =>
            argument.Kind == "union" ? string.Join("Or", argument.Variants!.Select(ArgumentName)) :
            argument.Name ?? NpmNames.ValueNameFor(argument.Kind);

        private static bool SameType(NpmValueType first, NpmValueType second) => SameType(first, second, null);

        private static bool SameType(NpmValueType first, NpmValueType second, Func<string, string, bool>? sameTypeParameter)
        {
            if (first.Kind != second.Kind || first.ReadOnly != second.ReadOnly ||
                ResultKey(first) != ResultKey(second) || first.ProtocolKey != second.ProtocolKey ||
                !SameSequence(first.ValueTypeParameters ?? [], second.ValueTypeParameters ?? [], StringComparer.Ordinal.Equals) ||
                !SameSequence(first.TypeParameters ?? [], second.TypeParameters ?? [], StringComparer.Ordinal.Equals))
                return false;
            if (sameTypeParameter is not null && first.Kind is "typeParameter" or "recordTypeParameter")
                return sameTypeParameter(first.Name!, second.Name!);
            if (first.Name != second.Name)
                return false;

            bool SameNested(NpmValueType left, NpmValueType right) => SameType(left, right, sameTypeParameter);
            bool SameField(NpmValueMember left, NpmValueMember right) => SameMember(left, right, sameTypeParameter);
            bool SameCallable(NpmValueSignature left, NpmValueSignature right) => SameSignature(left, right, sameTypeParameter);

            return first.Kind switch
            {
                "stringEnum" => first.StringLiterals!.SequenceEqual(second.StringLiterals!, StringComparer.Ordinal),
                "numberLiterals" => first.TypeIdentity == second.TypeIdentity &&
                    OrderedNumberLiterals(first).SequenceEqual(OrderedNumberLiterals(second)),
                "enum" => (first.EnumMembers ?? []).SequenceEqual(second.EnumMembers ?? []),
                "handle" or "namedRecord" => SameSequence(first.TypeArguments ?? [], second.TypeArguments ?? [], SameNested),
                "enrichedRef" when NominalKey.IsNamedRef(first) =>
                    SameSequence(first.TypeArguments ?? [], second.TypeArguments ?? [], SameNested),
                "ref" or "enrichedRef" => SameNested(first.ElementType!, second.ElementType!) &&
                    (first.WriteType is null ? second.WriteType is null :
                        second.WriteType is not null && SameNested(first.WriteType, second.WriteType)) &&
                    SameSequence(first.Members ?? [], second.Members ?? [], SameField),
                "array" or "inputArray" or "recordArray" or "dictionary" or "inputDictionary" or "readonlyDictionary" or "writableDictionary" or "partialRecord" or "unwrappedRecord" or "nullable" or "nullableSlot" or "undefinedable" or "optionalSlot" or "promise" => SameNested(first.ElementType!, second.ElementType!),
                "union" => SameSequence(first.Variants!, second.Variants!, SameNested),
                "formPathMap" => first.VeeValidatePath == second.VeeValidatePath && first.ArrayIndices == second.ArrayIndices &&
                    SameNested(first.ElementType!, second.ElementType!) &&
                    SameSequence(first.TypeArguments!, second.TypeArguments!, SameNested),
                "object" or "tupleView" => SameSequence(first.TypeArguments ?? [], second.TypeArguments ?? [], SameNested) &&
                    SameSequence(first.Members!, second.Members!, SameField),
                "callableHandle" => SameSequence(first.Signatures!, second.Signatures!, SameCallable) &&
                    SameSequence(first.Members!, second.Members!, SameField),
                "vuePlugin" => SameSequence(first.TypeArguments ?? [], second.TypeArguments ?? [], SameNested) &&
                    SameSequence(first.Members ?? [], second.Members ?? [], SameField),
                "action" or "function" or "method" => SameSequence(first.Signatures!, second.Signatures!, SameCallable),
                "propertyPath" or "propertyKey" => first.VeeValidatePath == second.VeeValidatePath &&
                    first.ArrayIndices == second.ArrayIndices &&
                    first.RequirePlainRecord == second.RequirePlainRecord &&
                    first.RequireRecordView == second.RequireRecordView &&
                    SameNested(first.ElementType!, second.ElementType!) &&
                    SameSequence(first.Variants!, second.Variants!, SameNested),
                _ => true,
            };
        }

        private static bool SameMember(NpmValueMember first, NpmValueMember second, Func<string, string, bool>? sameTypeParameter) =>
            first.Name == second.Name && first.Optional == second.Optional && first.ReadOnly == second.ReadOnly &&
            first.FixedBoolean == second.FixedBoolean && first.JsName == second.JsName && first.StaticKey == second.StaticKey &&
            first.StaticListArity == second.StaticListArity &&
            SameType(first.Type, second.Type, sameTypeParameter);

        private static bool SameSignature(NpmValueSignature first, NpmValueSignature second, Func<string, string, bool>? sameTypeParameter) =>
            SameType(first.ReturnType, second.ReturnType, sameTypeParameter) &&
            SameSequence(first.Parameters, second.Parameters, (left, right) => SameParameter(left, right, sameTypeParameter)) &&
            SameSequence(first.TypeParameters ?? [], second.TypeParameters ?? [], StringComparer.Ordinal.Equals) &&
            SameSequence(first.ReferenceTypeParameters ?? [], second.ReferenceTypeParameters ?? [], StringComparer.Ordinal.Equals) &&
            SameSequence(first.ValueTypeParameters ?? [], second.ValueTypeParameters ?? [], StringComparer.Ordinal.Equals);

        private static bool SameParameter(NpmValueParameter first, NpmValueParameter second, Func<string, string, bool>? sameTypeParameter) =>
            first.Name == second.Name && first.Optional == second.Optional && first.ReadOnlyReference == second.ReadOnlyReference &&
            first.FixedBoolean == second.FixedBoolean && first.FixedUndefined == second.FixedUndefined &&
            first.OptionalCallback == second.OptionalCallback && first.RestCallback == second.RestCallback &&
            SameType(first.Type, second.Type, sameTypeParameter);

        private static bool SameSequence<T>(IReadOnlyList<T> first, IReadOnlyList<T> second, Func<T, T, bool> same) =>
            first.Count == second.Count && first.Zip(second, same).All(equal => equal);
    }
}

internal sealed class NpmValueLowering(
    IReadOnlyDictionary<ISymbol, NpmValueExport> exports,
    IReadOnlyDictionary<ISymbol, NpmDefinition> definitions) : SemanticWalkerHost
{
    internal IReadOnlyDictionary<ISymbol, NpmDefinition> Definitions => definitions;

    public override Expression? RewriteInvocation(IInvocationOperation operation, SenseArgument argument, Expression? instance, IReadOnlyList<Expression> arguments) =>
        exports.TryGetValue(operation.TargetMethod.OriginalDefinition, out var export)
            ? new CallExpression(Import(export, argument), NodeList.From(arguments), optional: false)
            : null;

    public override Expression? RewriteMethodReferencePreorder(IMethodReferenceOperation operation, SenseArgument argument) =>
        exports.TryGetValue(operation.Method.OriginalDefinition, out var export) ? Import(export, argument) : null;

    public override Expression? RewritePropertyReference(IPropertyReferenceOperation operation, SenseArgument argument, Expression? instance, IReadOnlyList<Expression> arguments)
        => exports.TryGetValue(operation.Property.OriginalDefinition, out var export) ? Import(export, argument) : null;

    private static Identifier Import(NpmValueExport export, SenseArgument argument) =>
        argument.BindExternalImportSpecifier(export.ModuleSpecifier, export.ExportName, forceAlias: true);
}
