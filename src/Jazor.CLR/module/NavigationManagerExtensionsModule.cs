	private static string RebuildQuery(string uri, Array<Array<object?>> updates)
	{
		if (uri is null)
			throw new Error("ArgumentNullException: uri is null.");

		var hashIndex = uri.IndexOf("#", StringComparison.Ordinal);
		var hash = hashIndex < 0 ? "" : uri[hashIndex..];
		var beforeHash = hashIndex < 0 ? uri : uri[..hashIndex];
		var queryIndex = beforeHash.IndexOf("?", StringComparison.Ordinal);
		var prefix = queryIndex < 0 ? beforeHash : beforeHash[..queryIndex];
		var query = queryIndex < 0 ? "" : beforeHash[(queryIndex + 1)..];
		var emitted = new Array<string>();
		var consumed = new Array<Number>();
		// JavaScript sparse-array reads produce undefined. Each update must start at the
		// numeric offset zero so a newly supplied scalar is emitted on its first pass.
		for (var updateIndex = 0; updateIndex < updates.Length; updateIndex++)
			consumed.Push(0);

		if (query.Length != 0)
		{
			var entries = query.Split("&");
			for (var entryIndex = 0; entryIndex < entries.Length; entryIndex++)
			{
				var entry = entries[entryIndex];
				if (entry.Length == 0)
					continue;

				var equalsIndex = entry.IndexOf("=", StringComparison.Ordinal);
				var encodedName = equalsIndex < 0 ? entry : entry[..equalsIndex];
				var updateIndex = FindUpdateIndex(updates, encodedName);
				if (updateIndex < 0)
				{
					emitted.Push(entry);
					continue;
				}

				AppendNextValue(emitted, updates[updateIndex], consumed[updateIndex]);
				consumed[updateIndex]++;
			}
		}

		for (var updateIndex = 0; updateIndex < updates.Length; updateIndex++)
		{
			var update = updates[updateIndex];
			while (AppendNextValue(emitted, update, consumed[updateIndex]))
				consumed[updateIndex]++;
		}

		return prefix + (emitted.Length == 0 ? "" : "?" + emitted.Join("&")) + hash;
	}

	private static int FindUpdateIndex(Array<Array<object?>> updates, string encodedName)
	{
		for (var index = 0; index < updates.Length; index++)
		{
			if (encodedName.ToLower() == EscapeQueryComponent((string)updates[index][0]!).ToLower())
				return index;
		}
		return -1;
	}

	private static bool AppendNextValue(Array<string> emitted, Array<object?> update, Number offset)
	{
		var name = (string)update[0]!;
		var suppliedValue = update[1];
		if (suppliedValue is null)
			return false;

		if (Array<object?>.IsArray(suppliedValue))
		{
			var values = (Array<object?>)suppliedValue;
			if (offset >= values.Length)
				return false;

			var value = values[offset];
