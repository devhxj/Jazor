				emitted.Push(EscapeQueryComponent(name) + "=" + EscapeQueryComponent(FormatQueryValue(value)));
			return true;
		}

		if (offset != 0)
			return false;

		emitted.Push(EscapeQueryComponent(name) + "=" + EscapeQueryComponent(FormatQueryValue(suppliedValue)));
		return true;
	}

